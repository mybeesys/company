<?php

namespace Modules\Employee\Support;

/**
 * Sidebar «شركاتي» (/my-companies). Show-only. Navbar company switch stays ungated.
 */
final class MyCompaniesPermissions
{
    public const SHOW = 'my_companies.My companies.show';

    /**
     * @return list<array{name: string, name_ar: string, description: string, description_ar: string, type: string}>
     */
    public static function definitions(): array
    {
        $rows = array_filter(
            include base_path('Modules/Employee/data/dashboard-permissions.php'),
            static fn (array $row): bool => str_starts_with((string) ($row['name'] ?? ''), 'my_companies.')
        );

        $unique = [];
        foreach ($rows as $row) {
            $name = (string) ($row['name'] ?? '');
            if ($name === '' || isset($unique[$name])) {
                continue;
            }
            $unique[$name] = $row;
        }

        return array_values($unique);
    }
}
